-- Apply after rls-policies.sql.
-- Adds a role-2 account deletion approval queue. Authentication users are not
-- modified by this migration.

create table if not exists public.account_deletion_requests (
  id bigint generated by default as identity primary key,
  requested_by uuid not null,
  target_user_id uuid not null,
  status varchar(20) not null default 'PENDING'
    check (status in ('PENDING', 'APPROVED', 'REJECTED', 'EXECUTING', 'COMPLETED')),
  reviewed_by uuid,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint account_deletion_requests_not_self
    check (requested_by <> target_user_id)
);

create index if not exists idx_account_deletion_requests_requester
  on public.account_deletion_requests (requested_by, created_at desc);

create index if not exists idx_account_deletion_requests_pending
  on public.account_deletion_requests (status, created_at)
  where status in ('PENDING', 'APPROVED', 'EXECUTING');

create unique index if not exists idx_account_deletion_requests_active_target
  on public.account_deletion_requests (target_user_id)
  where status in ('PENDING', 'APPROVED', 'EXECUTING');

alter table public.account_deletion_requests enable row level security;

grant select on public.account_deletion_requests to authenticated;
grant usage, select on sequence public.account_deletion_requests_id_seq
  to service_role;
revoke insert, update, delete on public.account_deletion_requests
  from anon, authenticated;

drop policy if exists drikapex_account_deletion_requests_read
  on public.account_deletion_requests;
create policy drikapex_account_deletion_requests_read
  on public.account_deletion_requests
  for select to authenticated
  using (
    public.drikapex_is_owner()
    or requested_by = auth.uid()
  );
